"""Profile the raw data before any modelling and write docs/data_profile.md.

This runs on the raw CSV with pandas on purpose: it is the first look at the data and
should not depend on any transformation that comes later.
"""
from __future__ import annotations

import pandas as pd

from src.mdutil import fmt_int, fmt_num, fmt_pct, md_table
from src.paths import DOCS_DIR, RAW_CSV

LOW_N_THRESHOLD = 50
TIER_ORDER = ["Blue", "Silver", "Gold", "Platinum"]
TENURE_ORDER = ["13-24", "25-36", "37-48", "49+"]
CATEGORICAL = ["Attrition_Flag", "Gender", "Education_Level", "Marital_Status",
               "Income_Category", "Card_Category"]
NUMERIC_KEY = ["Customer_Age", "Months_on_book", "Months_Inactive_12_mon", "Credit_Limit",
               "Total_Trans_Amt", "Total_Trans_Ct", "Total_Amt_Chng_Q4_Q1",
               "Total_Ct_Chng_Q4_Q1"]


def tenure_band(months: pd.Series) -> pd.Series:
    return pd.cut(months, bins=[12, 24, 36, 48, 10_000], labels=TENURE_ORDER).astype(str)


def load_raw() -> pd.DataFrame:
    df = pd.read_csv(RAW_CSV)
    return df.drop(columns=[c for c in df.columns if c.startswith("Naive_Bayes_Classifier")])


def build_profile(df: pd.DataFrame) -> str:
    n = len(df)
    out: list[str] = []
    add = out.append

    add("# Data profile\n")
    add("Generated by `src/profile_data.py` from `data/raw/BankChurners.csv`. "
        "Do not edit by hand, rerun the script.\n")

    add("## Shape and keys\n")
    add(f"- Rows: {fmt_int(n)}")
    add(f"- Columns after dropping the two `Naive_Bayes_Classifier` columns: {df.shape[1]}")
    add(f"- Duplicate `CLIENTNUM` values: {fmt_int(df['CLIENTNUM'].duplicated().sum())}")
    add(f"- Null cells in the whole file: {fmt_int(df.isna().sum().sum())}\n")
    add("There are no true nulls. Missing information is stored as the text value "
        "\"Unknown\" in three columns, shown next.\n")

    add("## \"Unknown\" categories\n")
    rows = []
    for col in CATEGORICAL:
        unknown = int((df[col] == "Unknown").sum())
        rows.append([f"`{col}`", df[col].nunique(), fmt_int(unknown), fmt_pct(unknown / n)])
    add(md_table(pd.DataFrame(rows, columns=["Column", "Distinct values", "Unknown rows",
                                             "Unknown share"]),
                 align_right=["Distinct values", "Unknown rows", "Unknown share"]))
    add("\nNone of the columns with \"Unknown\" values is used in the decomposition, so "
        "these rows are kept as they are. They only matter if someone slices the "
        "dashboard by education, marital status or income.\n")

    add("## Categorical distributions\n")
    for col in CATEGORICAL:
        counts = df[col].value_counts()
        table = pd.DataFrame({
            col: counts.index,
            "Customers": [fmt_int(v) for v in counts.values],
            "Share": [fmt_pct(v / n) for v in counts.values],
        })
        add(md_table(table, align_right=["Customers", "Share"]))
        add("")

    add("## Numeric distributions (columns used in the analysis)\n")
    desc = df[NUMERIC_KEY].describe(percentiles=[0.05, 0.25, 0.5, 0.75, 0.95]).T
    table = pd.DataFrame({
        "Column": [f"`{c}`" for c in desc.index],
        "Min": [fmt_num(v) for v in desc["min"]],
        "P5": [fmt_num(v) for v in desc["5%"]],
        "P25": [fmt_num(v) for v in desc["25%"]],
        "Median": [fmt_num(v) for v in desc["50%"]],
        "Mean": [fmt_num(v) for v in desc["mean"]],
        "P75": [fmt_num(v) for v in desc["75%"]],
        "P95": [fmt_num(v) for v in desc["95%"]],
        "Max": [fmt_num(v) for v in desc["max"]],
    })
    add(md_table(table, align_right=list(table.columns[1:])))
    add("")

    add("## Things that affect the method\n")
    amt_r, ct_r = df["Total_Amt_Chng_Q4_Q1"], df["Total_Ct_Chng_Q4_Q1"]
    zero_ct = int((ct_r == 0).sum())
    zero_amt = int((amt_r == 0).sum())
    inconsistent = int(((ct_r == 0) & (amt_r > 0)).sum())
    zero_ct_attrited = int(((ct_r == 0) & (df["Attrition_Flag"] == "Attrited Customer")).sum())
    at_36 = int((df["Months_on_book"] == 36).sum())
    max_limit = df["Credit_Limit"].max()
    at_max_limit = int((df["Credit_Limit"] == max_limit).sum())
    add(f"- **No quarterly levels.** The file has 12-month totals (`Total_Trans_Amt`, "
        f"`Total_Trans_Ct`) and Q4/Q1 ratios. Q1 and Q4 have to be derived. See `ASSUMPTIONS.md`.")
    add(f"- **Everyone transacts.** The smallest 12-month transaction count is "
        f"{fmt_int(df['Total_Trans_Ct'].min())}. No customer is dormant for the whole year.")
    add(f"- **Zero Q4 activity is rare.** {zero_ct} customers have a Q4/Q1 count ratio of "
        f"zero, meaning no Q4 transactions. {zero_ct_attrited} of those {zero_ct} are attrited "
        f"customers. The active rate therefore barely moves between quarters.")
    add(f"- **Inconsistent rows.** {zero_amt} customers have an amount ratio of zero and "
        f"{zero_ct} have a count ratio of zero. {inconsistent} customers have a zero count "
        f"ratio with a positive amount ratio, which cannot both be true. Rule used: no "
        f"transactions means no spend, so Q4 spend is set to zero for them.")
    add(f"- **Ratios above 1.** {fmt_pct((amt_r > 1).mean())} of customers spent more in Q4 "
        f"than in Q1 and {fmt_pct((ct_r > 1).mean())} transacted more often. Most customers "
        f"declined.")
    add(f"- **Tenure spike.** {fmt_int(at_36)} customers ({fmt_pct(at_36 / n)}) have exactly "
        f"36 months on book. That is far more than the neighbouring values and looks like "
        f"imputation by the data provider. It inflates the 25-36 tenure band.")
    add(f"- **Top-coded credit limit.** {fmt_int(at_max_limit)} customers sit at the maximum "
        f"credit limit of {fmt_num(max_limit, 0)}. Credit limit is not used in the decomposition.\n")

    add("## Segment sizes\n")
    df = df.assign(tenure_band=tenure_band(df["Months_on_book"]))

    add("### By card tier\n")
    tier = df.groupby("Card_Category").agg(
        customers=("CLIENTNUM", "size"),
        attrited=("Attrition_Flag", lambda s: (s == "Attrited Customer").sum()),
        annual_spend=("Total_Trans_Amt", "sum"),
    ).reindex(TIER_ORDER)
    table = pd.DataFrame({
        "Tier": tier.index,
        "Customers": [fmt_int(v) for v in tier["customers"]],
        "Share of customers": [fmt_pct(v / n) for v in tier["customers"]],
        "Share of 12-month spend": [fmt_pct(v / tier["annual_spend"].sum())
                                    for v in tier["annual_spend"]],
        "Attrition rate": [fmt_pct(a / c) for a, c in zip(tier["attrited"], tier["customers"])],
    })
    add(md_table(table, align_right=list(table.columns[1:])))
    add("\nPlatinum (20 customers) and Gold (116 customers) are tiny. Any number for them, "
        "especially by tenure band, is a description of a handful of people and not a "
        "pattern.\n")

    add("### By tenure band\n")
    ten = df.groupby("tenure_band").agg(
        customers=("CLIENTNUM", "size"),
        attrited=("Attrition_Flag", lambda s: (s == "Attrited Customer").sum()),
        min_months=("Months_on_book", "min"),
        max_months=("Months_on_book", "max"),
    ).reindex(TENURE_ORDER)
    table = pd.DataFrame({
        "Tenure band (months)": ten.index,
        "Observed range": [f"{a}-{b}" for a, b in zip(ten["min_months"], ten["max_months"])],
        "Customers": [fmt_int(v) for v in ten["customers"]],
        "Share of customers": [fmt_pct(v / n) for v in ten["customers"]],
        "Attrition rate": [fmt_pct(a / c) for a, c in zip(ten["attrited"], ten["customers"])],
    })
    add(md_table(table, align_right=list(table.columns[2:])))
    add("")

    add("### Tier x tenure cells\n")
    cells = df.groupby(["Card_Category", "tenure_band"]).agg(
        customers=("CLIENTNUM", "size"),
        existing=("Attrition_Flag", lambda s: (s == "Existing Customer").sum()),
    )
    rows = []
    for t in TIER_ORDER:
        for b in TENURE_ORDER:
            if (t, b) in cells.index:
                c, e = int(cells.loc[(t, b), "customers"]), int(cells.loc[(t, b), "existing"])
            else:
                c, e = 0, 0
            if c == 0:
                flag = "empty cell"
            elif c < LOW_N_THRESHOLD:
                flag = "low n, not interpreted"
            else:
                flag = "ok"
            rows.append([t, b, fmt_int(c), fmt_int(e), flag])
    table = pd.DataFrame(rows, columns=["Tier", "Tenure band", "Customers (Q1 book)",
                                        "Existing customers (scenario B Q4 book)", "Flag"])
    add(md_table(table, align_right=["Customers (Q1 book)",
                                     "Existing customers (scenario B Q4 book)"]))
    low = sum(1 for r in rows if r[4] == "low n, not interpreted")
    empty = sum(1 for r in rows if r[4] == "empty cell")
    ok = sum(1 for r in rows if r[4] == "ok")
    add(f"\nOf the 16 possible cells, {ok} have at least {LOW_N_THRESHOLD} customers, "
        f"{low} are flagged \"low n, not interpreted\" and {empty} "
        f"{'is' if empty == 1 else 'are'} empty. The low-n flag is based on the Q1 book "
        f"(all customers). Every Platinum cell and every Gold cell except 25-36 is low n.\n")

    return "\n".join(out) + "\n"


def main() -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    text = build_profile(load_raw())
    (DOCS_DIR / "data_profile.md").write_text(text, encoding="utf-8")
    print(f"Wrote {DOCS_DIR / 'data_profile.md'}")


if __name__ == "__main__":
    main()
